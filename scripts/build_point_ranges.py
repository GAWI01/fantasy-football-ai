"""Build the point-range table: what players with a given expected score actually scored.

Source: the out-of-sample 2024-25 backtest (forecast and actual points per player
per Gameweek). Rows are grouped by forecast, then indexed by the points those
groups *actually* averaged, so the table maps an expected score to a realistic
spread whatever the scale of the model that made the backtest. Only summary
quantiles are written; no raw FPL data.

    python scripts/build_point_ranges.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "backtesting" / "reports" / "c3_full_backtest_2024-25.csv"
BACKEND_OUT = ROOT / "backend" / "data" / "point_ranges.json"
FRONTEND_OUT = ROOT / "frontend" / "lib" / "model" / "pointRanges.data.ts"
BANDS = [0, 0.25, 0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 4.5, 5, 5.5, 6, 7, 30]


def build() -> list[dict[str, float]]:
    frame = pd.read_csv(SOURCE)
    frame["band"] = pd.cut(frame["predicted_points"], BANDS, right=False)
    rows = []
    for _, group in frame.groupby("band", observed=True):
        actual = group["actual_points"]
        rows.append({
            "n": int(len(actual)),
            "mean": round(float(actual.mean()), 3),
            "p10": float(actual.quantile(0.10)),
            "p25": float(actual.quantile(0.25)),
            "p50": float(actual.quantile(0.50)),
            "p75": float(actual.quantile(0.75)),
            "p90": float(actual.quantile(0.90)),
            "haul": round(float((actual >= 10).mean()), 3),
            "blank": round(float((actual <= 2).mean()), 3),
        })
    # Keep the table monotonic in its mean so interpolation is well defined.
    clean: list[dict[str, float]] = []
    for row in rows:
        if clean and row["mean"] <= clean[-1]["mean"]:
            previous = clean.pop()
            total = previous["n"] + row["n"]
            row = {key: (row[key] * row["n"] + previous[key] * previous["n"]) / total if key != "n" else total
                   for key in row}
        clean.append({key: (int(value) if key == "n" else round(float(value), 3)) for key, value in row.items()})
    # Small top groups are noisy: a higher expected score never gets a lower quantile.
    for index in range(1, len(clean)):
        for key in ("p10", "p25", "p50", "p75", "p90", "haul"):
            clean[index][key] = max(clean[index][key], clean[index - 1][key])
        clean[index]["blank"] = min(clean[index]["blank"], clean[index - 1]["blank"])
    return clean


def main() -> None:
    table = build()
    payload = {"source": "Out-of-sample 2024-25 backtest; quantiles of actual points by expected points.", "rows": table}
    BACKEND_OUT.write_text(json.dumps(payload, indent=1) + "\n")
    FRONTEND_OUT.write_text(
        "// Generated by scripts/build_point_ranges.py. Do not edit by hand.\n"
        "// What players with a given expected score actually scored (2024-25 backtest).\n"
        f"export const POINT_RANGE_ROWS = {json.dumps(table, indent=1)} as const;\n"
    )
    print(f"{len(table)} rows -> {BACKEND_OUT.relative_to(ROOT)}, {FRONTEND_OUT.relative_to(ROOT)}")
    for row in table:
        print(row)


if __name__ == "__main__":
    main()
